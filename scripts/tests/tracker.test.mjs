import { scoreItems, backtest, changeOver, scoreAskFacts } from "../lib/tracker.mjs";
let fail = 0;
const t = (n, c) => { if (c) console.log("  ok ", n); else { fail++; console.error("  FAIL", n); } };
const L = (vals) => vals.map((v, i) => [`2026-10-0${i + 1}`, v]);
const listings = new Map([[1, L([100, 90, 80])], [2, L([100, 110, 120])], [3, L([100, 90, 80])]]);
const prices = new Map([[1, L([10, 10, 10.5])], [2, L([10, 11, 12])], [3, L([10, 9, 8])]]);
const s = scoreItems({ listings, prices, asOf: "2026-10-03" });
t("falling listings with a steady price is picked", s.some((r) => r.pid === 1));
t("rising listings are not picked", !s.some((r) => r.pid === 2));
t("a falling price is not picked", !s.some((r) => r.pid === 3));
t("fewer than 3 nights is not scored", scoreItems({ listings: new Map([[1, L([100, 90])]]), prices, asOf: "2026-10-03" }).length === 0);
t("change over a window", Math.round(changeOver(L([10, 11]), "2026-10-01", "2026-10-02")) === 10);
const px = new Map();
for (let i = 0; i < 30; i++) px.set(i, [["2026-01-01", 10], ["2026-01-08", i < 5 ? 11 : 10]]);
const few = backtest([{ date: "2026-01-01", pid: 0 }], px, "2026-01-08");
t("no rate under n=20", few["7d"].n === 1 && few["7d"].rate === null);
const many = backtest(Array.from({ length: 20 }, (_, i) => ({ date: "2026-01-01", pid: i })), px, "2026-01-08");
t("rate once n=20, hit needs 3% and beating the median", many["7d"].n === 20 && many["7d"].hits === 5 && many["7d"].rate === 25);
t("an unfinished horizon is not scored", many["30d"].n === 0);
t("ask facts do not change scoreItems", scoreAskFacts([{ id: "sv3pt5-upc", ebayMedianAsk: 936.99 }], {}).feedScore === false && scoreItems({ listings, prices, asOf: "2026-10-03" }).length === s.length);
process.exit(fail ? 1 : 0);
